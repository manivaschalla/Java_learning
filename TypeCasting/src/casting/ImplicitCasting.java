package casting;

public class ImplicitCasting {
	public static void main(String[] args) {
		
		
		byte num1 = 100;
		
		short num2 = num1;
		
		int num3 = num2;
		
		long num4 = num3;
		
		float flo = 10.33f;
		
		double dob = flo;
		
		char ch = '*';
		
		int num5 = ch;
		System.out.println("Character : "+ch);
		System.out.println("ASCII value : "+ num5);
		
		
	}

}
