package operators;
/*
 * Used to compare two values. Returns boolean result:
	== : Equal to (a == b)
	!= : Not equal to (a != b)
	> : Greater than (a > b)
	< : Less than (a < b)
	>= : Greater than or equal to (a >= b)
	<= : Less than or equal to (a <= b)
 * 
 * 
 */



public class Relational {
	public static void main(String[] args) {
		int a =10, b = 5;
		System.out.println(a == b);
		System.out.println(a != b);
		System.out.println(a > b);
		System.out.println(a < b);
		System.out.println(a >= b);
		System.out.println(a <= b);

	}

}
